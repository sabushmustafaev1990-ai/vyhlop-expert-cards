def автоширина(ws, ширины):
    for i, w in enumerate(ширины, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def шапка(ws, колонки):
    ws.append(колонки)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.alignment = Alignment(vertical="center")
    ws.freeze_panes = "A2"


